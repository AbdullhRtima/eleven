// Copies the ledger-parsing block of ui/index.html (between the @ledger-core markers) into packages/ledger-core/index.js.
//   node scripts/extract-ledger-core.mjs           write the package
//   node scripts/extract-ledger-core.mjs --check   exit 1 if the package differs from the block (drift)
// No dependencies. The block is the source of truth: edit it in ui/index.html, then run this.
import fs from "node:fs";
import path from "node:path";
import url from "node:url";

const root = path.join(path.dirname(url.fileURLToPath(import.meta.url)), "..");
const UI = path.join(root, "ui", "index.html");
const OUT = path.join(root, "packages", "ledger-core", "index.js");
const START = "/* @ledger-core:start */", END = "/* @ledger-core:end */";

export function build(html) {
  const count = (m) => html.split(m).length - 1;
  if (count(START) !== 1 || count(END) !== 1) throw new Error(`ui/index.html must hold exactly one ${START} and one ${END}`);
  const a = html.indexOf(START) + START.length, b = html.indexOf(END);
  if (b < a) throw new Error("the end marker comes before the start marker");
  const body = html.slice(a, b).replace(/^\r?\n/, "").replace(/\s+$/, "") + "\n";
  const names = [...body.matchAll(/^(?:function\s+(\w+)|const\s+(\w+)\s*=)/gm)].map((m) => m[1] || m[2]);
  if (new Set(names).size !== names.length) throw new Error("duplicate top-level names in the block");
  return `// GENERATED by scripts/extract-ledger-core.mjs from the @ledger-core block in ui/index.html. Do not edit by hand.\n`
    + `// MIT. Pure ledger parsing: no DOM, no File System Access, no network.\n${body}\nexport { ${names.join(", ")} };\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === url.fileURLToPath(import.meta.url)) {
  const want = build(fs.readFileSync(UI, "utf8"));
  if (process.argv.includes("--check")) {
    const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : null;
    if (have !== want) { console.error("DRIFT: packages/ledger-core/index.js differs from the block in ui/index.html. Run: node scripts/extract-ledger-core.mjs"); process.exit(1); }
    console.log("ok: packages/ledger-core/index.js matches ui/index.html");
  } else {
    fs.mkdirSync(path.dirname(OUT), { recursive: true });
    fs.writeFileSync(OUT, want);
    console.log("wrote packages/ledger-core/index.js");
  }
}

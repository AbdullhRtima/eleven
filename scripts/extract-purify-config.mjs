// Copies the DOMPurify config of ui/index.html (between the @purify-config markers: the PURIFY object and the hooks) into
// packages/ledger-core/purify-config.js, so the phone PWA can sanitise ledger Markdown with the same rules.
//   node scripts/extract-purify-config.mjs           write the file
//   node scripts/extract-purify-config.mjs --check   exit 1 if the file differs from the block (drift)
// No dependencies. The block is the source of truth: edit it in ui/index.html, then run this.
import fs from "node:fs";
import path from "node:path";
import url from "node:url";

const root = path.join(path.dirname(url.fileURLToPath(import.meta.url)), "..");
const UI = path.join(root, "ui", "index.html");
const OUT = path.join(root, "packages", "ledger-core", "purify-config.js");
const START = "/* @purify-config:start */", END = "/* @purify-config:end */";

export function build(html) {
  const count = (m) => html.split(m).length - 1;
  if (count(START) !== 1 || count(END) !== 1) throw new Error(`ui/index.html must hold exactly one ${START} and one ${END}`);
  const a = html.indexOf(START) + START.length, b = html.indexOf(END);
  if (b < a) throw new Error("the end marker comes before the start marker");
  const body = html.slice(a, b).replace(/^\r?\n/, "").replace(/\s+$/, "");
  if (!/^const PURIFY = \{/m.test(body)) throw new Error("the block must define const PURIFY");
  // The block is copied verbatim. It reads `window.DOMPurify` and `DOMPurify`, so it runs inside a function that shadows `window`
  // with { DOMPurify }: the caller passes in the DOMPurify instance (browser global, or a jsdom-backed one) and gets the PURIFY config back.
  const indented = body.split("\n").map((l) => (l ? "  " + l : l)).join("\n");
  return `// GENERATED by scripts/extract-purify-config.mjs from the @purify-config block in ui/index.html. Do not edit by hand.\n`
    + `// MIT. The DOMPurify rules for untrusted ledger Markdown: configurePurify(DOMPurify) registers the hooks on that instance and\n`
    + `// returns the config object to pass to DOMPurify.sanitize(html, config).\n`
    + `export function configurePurify(DOMPurify) {\n  const window = { DOMPurify };\n${indented}\n  return PURIFY;\n}\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === url.fileURLToPath(import.meta.url)) {
  const want = build(fs.readFileSync(UI, "utf8"));
  if (process.argv.includes("--check")) {
    const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : null;
    if (have !== want) { console.error("DRIFT: packages/ledger-core/purify-config.js differs from the block in ui/index.html. Run: node scripts/extract-purify-config.mjs"); process.exit(1); }
    console.log("ok: packages/ledger-core/purify-config.js matches ui/index.html");
  } else {
    fs.mkdirSync(path.dirname(OUT), { recursive: true });
    fs.writeFileSync(OUT, want);
    console.log("wrote packages/ledger-core/purify-config.js");
  }
}
